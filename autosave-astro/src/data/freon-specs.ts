// Helper functions for programmatic querying
export function getAllFreonSpecs(): FreonVehicleSpec[] {
  return freonSpecs;
}

export function getFreonSpecsByBrand(brandSlug: string): FreonVehicleSpec[] {
  return freonSpecs.filter((spec) => spec.brandSlug.toLowerCase() === brandSlug.toLowerCase());
}

export function getFreonSpec(brandSlug: string, modelSlug: string): FreonVehicleSpec | undefined {
  return freonSpecs.find(
    (spec) =>
      spec.brandSlug.toLowerCase() === brandSlug.toLowerCase() &&
      spec.modelSlug.toLowerCase() === modelSlug.toLowerCase()
  );
}

export function getAllFreonBrands(): { brandSlug: string; brandNameAr: string; brandNameEn: string; count: number }[] {
  const brandMap = new Map<string, { brandNameAr: string; brandNameEn: string; count: number }>();

  for (const spec of freonSpecs) {
    const existing = brandMap.get(spec.brandSlug);
    if (existing) {
      existing.count += 1;
    } else {
      brandMap.set(spec.brandSlug, {
        brandNameAr: spec.brandNameAr,
        brandNameEn: spec.brandNameEn,
        count: 1,
      });
    }
  }

  return Array.from(brandMap.entries()).map(([brandSlug, val]) => ({
    brandSlug,
    brandNameAr: val.brandNameAr,
    brandNameEn: val.brandNameEn,
    count: val.count,
  }));
}
